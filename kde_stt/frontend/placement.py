"""Position the overlay on KDE Wayland.

Wayland compositors own top-level window placement, so the QML window's
``x``/``y`` values are ignored under KWin.  This module installs a tiny KWin
script (through KWin's scripting D-Bus API) that moves the overlay window to
the configured anchor on the active screen whenever it is shown.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

from PySide6.QtDBus import QDBus, QDBusConnection, QDBusMessage

SCRIPT_PATH = Path.home() / ".cache" / "kde-stt" / "overlay-position.js"
PLUGIN_NAME = "kde-stt-overlay-position"
CALL_TIMEOUT_MS = 2000


def _padding(button_size: int, margin: int, position: str) -> tuple[int, int, int, int]:
    glow = max(56, round(button_size * 0.36))
    return (
        min(glow, margin) if "left" in position else glow,
        min(glow, margin) if "right" in position else glow,
        min(glow, margin) if "top" in position else glow,
        min(glow, margin) if "bottom" in position else glow,
    )


def _script(position: str, button_size: int, margin: int) -> str:
    pad_left, pad_right, pad_top, pad_bottom = _padding(
        button_size, margin, position
    )
    return f"""\
// Generated by kde-stt-frontend. Do not edit.
var POSITION = {json.dumps(position)};
var MARGIN = {margin};
var PAD_LEFT = {pad_left};
var PAD_RIGHT = {pad_right};
var PAD_TOP = {pad_top};
var PAD_BOTTOM = {pad_bottom};

function isOverlay(w) {{
    return w && w.resourceClass === "kde-stt-frontend";
}}

function areaFor(w) {{
    var out = null;
    try {{
        if (workspace.activeWindow && workspace.activeWindow.output)
            out = workspace.activeWindow.output;
    }} catch (e) {{}}
    if (!out)
        out = w.output;
    if (!out)
        out = workspace.activeScreen;
    if (!out)
        return workspace.virtualScreenGeometry;
    try {{
        return workspace.clientArea(KWin.PlacementArea, out, workspace.currentDesktop);
    }} catch (e) {{
        return out.geometry;
    }}
}}

function place(w) {{
    if (!isOverlay(w))
        return;
    var area = areaFor(w);
    var ww = w.width;
    var wh = w.height;
    var x, y;

    if (POSITION.indexOf("left") >= 0)
        x = area.x + MARGIN - PAD_LEFT;
    else if (POSITION.indexOf("right") >= 0)
        x = area.x + area.width - ww - MARGIN + PAD_RIGHT;
    else
        x = area.x + (area.width - ww) / 2;

    if (POSITION.indexOf("top") >= 0)
        y = area.y + MARGIN - PAD_TOP;
    else if (POSITION.indexOf("bottom") >= 0)
        y = area.y + area.height - wh - MARGIN + PAD_BOTTOM;
    else
        y = area.y + (area.height - wh) / 2;

    x = Math.round(x);
    y = Math.round(y);
    if (Math.abs(w.x - x) < 1 && Math.abs(w.y - y) < 1)
        return;
    w.frameGeometry = {{x: x, y: y, width: ww, height: wh}};
}}

function watch(w) {{
    if (!isOverlay(w))
        return;
    try {{
        w.frameGeometryChanged.connect(function() {{ place(w); }});
    }} catch (e) {{}}
    try {{
        w.captionChanged.connect(function() {{ place(w); }});
    }} catch (e) {{}}
    place(w);
}}

try {{ workspace.windowAdded.connect(watch); }} catch (e) {{}}
try {{
    workspace.screensChanged.connect(function() {{
        var list = workspace.windowList();
        for (var i = 0; i < list.length; i++)
            place(list[i]);
    }});
}} catch (e) {{}}

var initial = workspace.windowList();
for (var i = 0; i < initial.length; i++)
    watch(initial[i]);
"""


def _call(
    bus: QDBusConnection,
    path: str,
    interface: str,
    method: str,
    args: list[object] | None = None,
) -> QDBusMessage:
    message = QDBusMessage.createMethodCall("org.kde.KWin", path, interface, method)
    if args:
        message.setArguments(args)
    return bus.call(message, QDBus.CallMode.Block, CALL_TIMEOUT_MS)


def _unload_previous(bus: QDBusConnection) -> None:
    reply = _call(
        bus, "/Scripting", "org.kde.kwin.Scripting", "isScriptLoaded", [PLUGIN_NAME]
    )
    if reply.type() == QDBusMessage.ErrorMessage:
        return
    loaded = bool(reply.arguments()[0]) if reply.arguments() else False
    if loaded:
        _call(
            bus,
            "/Scripting",
            "org.kde.kwin.Scripting",
            "unloadScript",
            [PLUGIN_NAME],
        )


def install(position: str, button_size: int, margin: int) -> bool:
    """Install (or refresh) the KWin positioning script.

    Returns True when the script was loaded.  Silently returns False when
    the session is not KDE Wayland or KWin's scripting service is absent.
    """
    if os.environ.get("XDG_SESSION_TYPE") != "wayland" and not os.environ.get(
        "WAYLAND_DISPLAY"
    ):
        return False
    try:
        return _install(position, button_size, margin)
    except Exception as exc:
        print(
            f"warning: could not set up KWin window positioning: {exc}",
            file=sys.stderr,
        )
        return False


def _install(position: str, button_size: int, margin: int) -> bool:
    bus = QDBusConnection.sessionBus()
    if not bus.isConnected():
        return False
    service = bus.interface().isServiceRegistered("org.kde.KWin")
    if not service.value():
        return False

    SCRIPT_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCRIPT_PATH.write_text(
        _script(position, button_size, margin), encoding="utf-8"
    )

    _unload_previous(bus)
    reply = _call(
        bus,
        "/Scripting",
        "org.kde.kwin.Scripting",
        "loadScript",
        [str(SCRIPT_PATH), PLUGIN_NAME],
    )
    if reply.type() == QDBusMessage.ErrorMessage or not reply.arguments():
        print(
            "warning: could not load the KWin overlay position script: "
            f"{reply.errorMessage()}",
            file=sys.stderr,
        )
        return False

    script_id = int(reply.arguments()[0])
    run = _call(
        bus,
        f"/Scripting/Script{script_id}",
        "org.kde.kwin.Script",
        "run",
    )
    if run.type() == QDBusMessage.ErrorMessage:
        print(
            "warning: could not start the KWin overlay position script: "
            f"{run.errorMessage()}",
            file=sys.stderr,
        )
        return False
    return True


def uninstall() -> None:
    """Unload the positioning script when the frontend exits."""
    try:
        _uninstall()
    except Exception:
        pass


def _uninstall() -> None:
    bus = QDBusConnection.sessionBus()
    if not bus.isConnected():
        return
    if not bus.interface().isServiceRegistered("org.kde.KWin").value():
        return
    _call(
        bus,
        "/Scripting",
        "org.kde.kwin.Scripting",
        "unloadScript",
        [PLUGIN_NAME],
    )

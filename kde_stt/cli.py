"""kde-stt — command line client / global shortcut command.

Used by the KDE custom shortcut (`kde-stt toggle`) and for manual control.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from typing import Any

from dbus_next.constants import BusType
from dbus_next.aio.message_bus import MessageBus

from . import BUS_IFACE, BUS_NAME, BUS_PATH


async def _iface() -> Any:
    bus = await MessageBus(bus_type=BusType.SESSION).connect()
    try:
        introspection = await bus.introspect(BUS_NAME, BUS_PATH)
    except Exception:
        print("kde-sttd is not running. Start it with: kde-sttd", file=sys.stderr)
        sys.exit(1)
    obj = bus.get_proxy_object(BUS_NAME, BUS_PATH, introspection)
    return obj.get_interface(BUS_IFACE)


async def _call(command: str, text: str = "") -> None:
    iface = await _iface()
    if command == "toggle":
        await iface.call_toggle()
    elif command == "start":
        await iface.call_start()
    elif command == "stop":
        await iface.call_stop()
    elif command == "cancel":
        await iface.call_cancel()
    elif command == "inject":
        await iface.call_inject(text)
    elif command == "status":
        status = await iface.call_status()
        print(json.dumps(json.loads(status), indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(prog="kde-stt", description="Global shortcut STT for Linux")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("toggle", help="start/stop recording")
    sub.add_parser("start", help="begin recording")
    sub.add_parser("stop", help="stop recording + transcribe")
    sub.add_parser("cancel", help="discard the current recording")
    sub.add_parser("status", help="print daemon state as JSON")
    inject = sub.add_parser("inject", help="debug: paste text into the focused window")
    inject.add_argument("text", help="text to paste")

    model = sub.add_parser("model", help="change the whisper model (tiny/base/small/medium/large-v3)")
    model.add_argument("name", help="model size")

    args = parser.parse_args()
    try:
        if args.command == "model":
            _switch_model(args.name)
        else:
            asyncio.run(_call(args.command, getattr(args, "text", "")))
    except KeyboardInterrupt:
        pass


def _switch_model(name: str) -> None:
    from .config import CONFIG_FILE, load_config

    if name not in {"tiny", "base", "small", "medium", "large-v3"}:
        print(f"unknown model: {name}", file=sys.stderr)
        sys.exit(1)
    cfg = load_config()
    cfg.transcriber.model = name
    if not CONFIG_FILE.exists():
        CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
        CONFIG_FILE.write_text(
            "# generated by kde-stt model\n"
            "[transcriber]\n"
            f'model = "{name}"\n',
            encoding="utf-8",
        )
    else:
        text = CONFIG_FILE.read_text(encoding="utf-8")
        lines = []
        in_transcriber = False
        for line in text.splitlines():
            if line.startswith("[transcriber]"):
                in_transcriber = True
            elif line.startswith("["):
                in_transcriber = False
            if in_transcriber and line.startswith("model"):
                lines.append(f'model = "{name}"')
            else:
                lines.append(line)
        CONFIG_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"model set to '{name}'. The daemon loads it on next transcription "
        "(restart kde-sttd to load it now)."
    )


if __name__ == "__main__":
    main()
